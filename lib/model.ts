// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// other rankable pre-token protocol below it: the early rows the radar exists to find. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); live-token
// protocols are kept apart and shown with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and no protocol name is ever
// special-cased: the same function scores every row.
//
//   comp       = the category's comp multiple: the MEDIAN market-cap-per-TVL of the snapshot's own
//                live-token protocols in the same category (at least 3 comps, else the whole
//                snapshot's median), floored at 0.05 and capped at 0.60. It answers "what does the
//                market pay per dollar of TVL for a protocol like this one?" with the snapshot's
//                own live market, not a guessed constant.
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.40
//   maturity   = 0.70 + min(age_days, 1460) / 1460 x 0.30   (age unknown: 365 days)
//   breadth    = 1 + min(chains - 1, 4) x 0.02            (wider distribution, capped)
//   implied    = max(1, round(tvl_usd x comp x growthMult x maturity x breadth))
//
// Say a protocol "records no token", never that it "has none": DefiLlama's record is not proof.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

